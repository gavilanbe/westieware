function tiny(g, s, x, y, col, o = {}) {
  s = String(s).toUpperCase(); const w = s.length * 4 - 1; let xx = rd(o.align === 'c' ? x - w / 2 : o.align === 'r' ? x - w : x); y = rd(y);
  g.fillStyle = col;
  for (const ch0 of s) {
    const ch = TINY_FOLD[ch0] || ch0, gl = TINY[ch];
    if (gl) gl.forEach((r, j) => { for (let i = 0; i < 3; i++) if (r[i] === '#') g.fillRect(xx + i, y + j, 1, 1); });
    if (ch0 === 'Ü') { g.fillRect(xx, y - 2, 1, 1); g.fillRect(xx + 2, y - 2, 1, 1); }
    else if (ch !== ch0) { g.fillRect(xx + 2, y - 3, 1, 1); g.fillRect(xx + 1, y - 2, 1, 1); }
    xx += 4;
  }
  return w;
}

// shrink a MORDISCO style until the word fits in maxW pixels
function fitMord(s, maxW, st) { st = Object.assign({}, st); let tries = 0; while (mordW(s, st) > maxW && st.u > .9 && tries++ < 12) { st.u = +(st.u * .92).toFixed(2); st.r = +(Math.max(1, st.r * .92)).toFixed(2); } return st; }
